import type { ContentBlockManifestEntry } from './contentBlocks.js'
import type { ProposalContentComparisonBar } from '../salesContent/types.js'

export interface InsightsSwot {
  strengths: string[]
  weaknesses: string[]
  risks: string[]
}

export const DEFAULT_INSIGHTS_BUSINESS_CURRENT_POSITION: ProposalContentComparisonBar[] = []
export const DEFAULT_INSIGHTS_BUSINESS_SWOT: InsightsSwot = { strengths: [], weaknesses: [], risks: [] }

function clampScore0to10(value: unknown): number {
  const n = typeof value === 'number' ? value : typeof value === 'string' ? parseFloat(value) : NaN
  if (!Number.isFinite(n)) return 0
  return Math.max(0, Math.min(10, Math.round(n)))
}

/** Backfills a stored `insightsBusiness.currentPosition` array to the full shape — same reasoning as normalizePricingCards/normalizeEnrichment: JSON.parse has no shape validation. */
export function normalizeCurrentPosition(raw: unknown): ProposalContentComparisonBar[] {
  if (!Array.isArray(raw)) return DEFAULT_INSIGHTS_BUSINESS_CURRENT_POSITION
  return raw
    .filter((d): d is Record<string, unknown> => Boolean(d) && typeof d === 'object')
    .map((d) => ({
      label: typeof d.label === 'string' ? d.label : '',
      currentScore: clampScore0to10(d.currentScore),
      targetScore: clampScore0to10(d.targetScore),
    }))
}

/** Parses the `insightsBusiness.currentPosition` contentOverride (a JSON array) — the one parse path all four render call sites (Editor, Review, ClientProposalView, PdfView) should share. */
export function parseCurrentPositionOverride(raw: string | undefined): ProposalContentComparisonBar[] {
  if (!raw) return DEFAULT_INSIGHTS_BUSINESS_CURRENT_POSITION
  try {
    return normalizeCurrentPosition(JSON.parse(raw))
  } catch {
    return DEFAULT_INSIGHTS_BUSINESS_CURRENT_POSITION
  }
}

/** Backfills a stored `insightsBusiness.swot` object to the full shape. */
export function normalizeSwot(raw: unknown): InsightsSwot {
  if (!raw || typeof raw !== 'object') return DEFAULT_INSIGHTS_BUSINESS_SWOT
  const obj = raw as Record<string, unknown>
  const arr = (key: string) => (Array.isArray(obj[key]) ? (obj[key] as unknown[]).filter((v): v is string => typeof v === 'string') : [])
  return { strengths: arr('strengths'), weaknesses: arr('weaknesses'), risks: arr('risks') }
}

/** Parses the `insightsBusiness.swot` contentOverride (a single JSON object, not an array) — shared by all four render call sites. */
export function parseSwotOverride(raw: string | undefined): InsightsSwot {
  if (!raw) return DEFAULT_INSIGHTS_BUSINESS_SWOT
  try {
    return normalizeSwot(JSON.parse(raw))
  } catch {
    return DEFAULT_INSIGHTS_BUSINESS_SWOT
  }
}

