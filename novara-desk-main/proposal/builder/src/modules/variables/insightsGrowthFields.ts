import type { ContentBlockManifestEntry } from './contentBlocks.js'
import type { ProposalContentOpportunityCard } from '../salesContent/types.js'

export const DEFAULT_INSIGHTS_GROWTH_OPPORTUNITIES: ProposalContentOpportunityCard[] = []

/** Backfills a stored `insightsGrowth.growthOpportunities` array to the full shape — same reasoning as normalizePricingCards/normalizeEnrichment: JSON.parse has no shape validation. */
export function normalizeGrowthOpportunities(raw: unknown): ProposalContentOpportunityCard[] {
  if (!Array.isArray(raw)) return DEFAULT_INSIGHTS_GROWTH_OPPORTUNITIES
  return raw
    .filter((c): c is Record<string, unknown> => Boolean(c) && typeof c === 'object')
    .map((c) => ({
      title: typeof c.title === 'string' ? c.title : '',
      description: typeof c.description === 'string' ? c.description : '',
    }))
}

/** Parses the `insightsGrowth.growthOpportunities` contentOverride (a JSON array) — the one parse path all four render call sites (Editor, Review, ClientProposalView, PdfView) should share. */
export function parseGrowthOpportunitiesOverride(raw: string | undefined): ProposalContentOpportunityCard[] {
  if (!raw) return DEFAULT_INSIGHTS_GROWTH_OPPORTUNITIES
  try {
    return normalizeGrowthOpportunities(JSON.parse(raw))
  } catch {
    return DEFAULT_INSIGHTS_GROWTH_OPPORTUNITIES
  }
}

